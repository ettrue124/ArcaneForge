    public static string Format(string text) => Regex.Replace(text, @"\{([^{}]+)\}", match => {
        string value=match.Groups[1].Value;
        string code=value.StartsWith("o",StringComparison.Ordinal)?value:
            value.Contains('/')?"o("+value+")":value=="S"?"oSi":"o"+value;
        return Symbols.TryGetValue(code,out var sprite)
            ? $"<sprite=\"SpriteSheet_ManaIcons\" name=\"{sprite}\" color=\"#FFFFFF\">"
            : match.Value;
    });
